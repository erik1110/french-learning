/** 把一個詞正規化成查表用的 key。 */
export function normalize(word) {
  return String(word)
    .toLowerCase()
    .replace(/[.,!?;:«»"()[\]…]/g, '')
    .replace(/[’]/g, "'")
    .trim()
}

/**
 * 查一個詞的解釋。查不到就試著去掉縮寫的冠詞（l'heure → heure），
 * 再試去掉複數的 s。都查不到就回 null，那個字就不會有底線。
 */
export function lookup(word) {
  const w = normalize(word)
  if (!w) return null
  // Try the whole token first so contractions keep their own entry — c'est
  // must not fall through to est, which would explain the wrong word.
  const tries = [w]
  const elided = w.replace(/^[a-zà-ÿ]{1,2}'/, '')
  if (elided !== w) tries.push(elided)
  if (w.endsWith('s') && w.length > 3) tries.push(w.slice(0, -1))
  for (const k of tries) {
    const hit = GLOSS[k]
    if (hit) return { word: k, pos: hit[0], note: hit[1] }
  }
  return null
}
